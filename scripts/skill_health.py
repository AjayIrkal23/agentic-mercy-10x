#!/usr/bin/env python3
"""skill_health.py — pushed-vs-invoked skill report and the `skillOverrides` map.

Reads the router's `<sid>.pushed-skills.jsonl` and the tracker's
`<sid>.skill-invocations.jsonl` (newest --window sessions), joins them with the
`skills/*/SKILL.md` inventory and the plugin entries of `hooks/skills-index.json`, and
prints a report (`--report`, default; `--json`) or writes the overrides file
(`--overrides --out PATH`) that integrate copies into settings.template.json. It never
writes settings. Replaces the retired weights loop and ECC's skills-health/context profiles.
"""
from __future__ import annotations

import argparse
import importlib.util
import json
import os
import re
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LEGAL = ("on", "name-only", "user-invocable-only")
MIN_WINDOW = 10
LITTER = {"s", "t", "w"}
# Higgsfield + kokonutui keep their descriptions since 2026-10-31 (owner): name-only hid the asset
# skills from description matching, so the model never picked them on its own.
NAME_ONLY_STATIC = ("mmx-cli", "lean-ctx", "workflow-audit")
ABOUT = ("generated by scripts/skill_health.py --overrides; integrate copies skillOverrides into "
         "settings.template.json; values emitted: on | name-only (never user-invocable-only, which hides a "
         "skill from the model); plugin skills cannot be overridden")
_SUFFIXES = (".pushed-skills.jsonl", ".skill-invocations.jsonl")


def _frontmatter_reader():
    try:
        spec = importlib.util.spec_from_file_location("skills_lib_sh", ROOT / "scripts" / "skills_lib.py")
        mod = importlib.util.module_from_spec(spec)
        spec.loader.exec_module(mod)  # type: ignore[union-attr]
        return mod.read_frontmatter
    except Exception:  # noqa: BLE001 — fall back to a minimal parser
        return _read_fm_fallback


def _read_fm_fallback(path: Path) -> tuple[dict, str, bool]:
    try:
        text = Path(path).read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        return {}, "", False
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n?(.*)$", text, re.DOTALL)
    if not m:
        return {}, text, False
    fm: dict = {}
    for ln in m.group(1).splitlines():
        km = re.match(r"^([A-Za-z0-9_-]+):\s*(.*)$", ln)
        if km:
            val = km.group(2).strip().strip('"').strip("'")
            fm[km.group(1)] = {"true": True, "false": False}.get(val.lower(), val)
    return fm, m.group(2), bool(fm)


def _truthy(v) -> bool:
    return v is True or (isinstance(v, str) and v.strip().lower() == "true")


def inventory(root: Path) -> dict:
    """{"local": {name: frontmatter}, "plugins": {name: description}}; raises OSError without skills/."""
    skills = root / "skills"
    if not skills.is_dir():
        raise OSError(f"no skills dir at {skills}")
    read = _frontmatter_reader()
    local = {}
    for p in sorted(skills.glob("*/SKILL.md")):
        fm, _, _ = read(p)
        fm = fm if isinstance(fm, dict) else {}
        local[str(fm.get("name") or p.parent.name)] = fm
    plugins = {}
    # the tracked index (local) and the per-machine plugin sidecar (state/skills-index.plugins.json)
    for rel in ("hooks/skills-index.json", "state/skills-index.plugins.json"):
        try:
            idx = json.loads((root / rel).read_text(encoding="utf-8"))
        except (OSError, ValueError):
            idx = {}
        idx = idx if isinstance(idx, dict) else {}
        for block in (idx, idx.get("skills") if isinstance(idx.get("skills"), dict) else {}):
            for k, v in block.items():
                if ":" in k and not k.startswith("_"):
                    plugins.setdefault(k, str((v or {}).get("description", "")) if isinstance(v, dict) else "")
    return {"local": local, "plugins": plugins}


def telemetry_dir(root: Path, override: str | None) -> Path:
    if override:
        return Path(override).expanduser()
    env = os.environ.get("CLAUDE_HOOK_TELEMETRY_DIR")
    return Path(env).expanduser() if env else root / "hooks" / ".telemetry"


def _rows(path: Path, notes: list[str]) -> tuple[list[dict], int]:
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except (OSError, UnicodeDecodeError) as exc:
        notes.append(f"unreadable {path.name}: {type(exc).__name__}")
        return [], 0
    rows, bad = [], 0
    for ln in lines:
        if not ln.strip():
            continue
        try:
            obj = json.loads(ln)
        except ValueError:
            bad += 1
            continue
        if isinstance(obj, dict):
            rows.append(obj)
        else:
            bad += 1
    return rows, bad


def collect(root: Path, tel: Path, window: int = 30) -> dict:
    inv = inventory(root)
    files: dict[str, dict[str, Path]] = {}
    if tel.is_dir():
        for p in tel.iterdir():
            for suf in _SUFFIXES:
                if p.name.endswith(suf):
                    sid = p.name[: -len(suf)]
                    if sid and not sid.startswith("doctor-") and sid not in LITTER:
                        files.setdefault(sid, {})[suf] = p
    newest = sorted(files, key=lambda s: (max(p.stat().st_mtime for p in files[s].values()), s), reverse=True)
    sids = newest[:window]
    pushed: dict[str, int] = {}
    invoked: dict[str, int] = {}
    notes: list[str] = []
    n_push = n_inv = skipped = 0
    for sid in sids:
        if _SUFFIXES[0] in files[sid]:
            rows, bad = _rows(files[sid][_SUFFIXES[0]], notes)
            skipped += bad
            n_push += len(rows)
            for r in rows:
                for s in r.get("skills") or []:
                    if isinstance(s, str):
                        pushed[s] = pushed.get(s, 0) + 1
        if _SUFFIXES[1] in files[sid]:
            rows, bad = _rows(files[sid][_SUFFIXES[1]], notes)
            skipped += bad
            n_inv += len(rows)
            for r in rows:
                s = r.get("skill")
                if isinstance(s, str) and s:
                    invoked[s] = invoked.get(s, 0) + 1
    stats = {}
    for name in sorted(set(inv["local"]) | set(pushed) | set(invoked)):
        p, i = pushed.get(name, 0), invoked.get(name, 0)
        flags = []
        if p and not i:
            flags.append("never-invoked")
        if i and not p:
            flags.append("never-pushed")
        if _truthy(inv["local"].get(name, {}).get("disable-model-invocation")):
            flags.append("dmi")
        if name in inv["plugins"]:
            flags.append("plugin")
        elif name not in inv["local"]:
            flags.append("missing")
        stats[name] = {"pushed": p, "invoked": i, "ratio": round(i / p, 3) if p else None, "flags": flags}
    return {"inventory": inv, "stats": stats, "window_sessions": len(sids), "pushed_rows": n_push,
            "invocation_rows": n_inv, "skipped_lines": skipped, "notes": notes}


def overrides(inventory, stats, window_sessions) -> dict:
    out = {}
    for name in sorted(inventory["local"]):
        if name.startswith("invoke-"):  # the 16 delegators (`invoke` itself stays on): the model calls them
            out[name] = "name-only"     # through Skill(), so never user-invocable-only, which hides them
        elif name in NAME_ONLY_STATIC:
            out[name] = "name-only"
        elif (window_sessions >= MIN_WINDOW and stats.get(name, {}).get("invoked", 0) == 0
              and _truthy(inventory["local"][name].get("disable-model-invocation"))):
            out[name] = "name-only"
    return out


def _core_skills(root: Path) -> set[str]:
    try:
        data = json.loads((root / "hooks" / "core-skill-set.json").read_text(encoding="utf-8"))
        return {str(e.get("skill")) for e in data.get("always", []) if isinstance(e, dict)}
    except (OSError, ValueError, AttributeError):
        return set()


def overrides_doc(data: dict, root: Path | None = None) -> dict:
    ov = overrides(data["inventory"], data["stats"], data["window_sessions"])
    warnings = []
    for name in sorted(_core_skills(root or ROOT)):
        if ov.get(name) == "name-only":  # the aggregator pointer needs the description
            ov[name] = "on"
            warnings.append(f"{name}: in hooks/core-skill-set.json, kept on")
    # settings.json may never contain the string lean-ctx (render.FORBIDDEN_SUBSTRING): the shipped
    # list leaves it out, so this file must not count it either
    if ov.pop("lean-ctx", None) is not None:
        warnings.append("lean-ctx: left out (settings.json must not name it; render.FORBIDDEN_SUBSTRING)")
    doc = {"_about": ABOUT, "generated_at": time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime()),
           "window_sessions": data["window_sessions"],
           "telemetry_rule_applied": data["window_sessions"] >= MIN_WINDOW,
           "policy": {"name-only": ["every invoke-* skill (the model calls them through Skill(); "
                                    "user-invocable-only would hide them)",
                                    f"NAME_ONLY_STATIC list + never-invoked dmi skills when the window holds "
                                    f">= {MIN_WINDOW} sessions"],
                      "never": "user-invocable-only (it hides the skill from the model's Skill tool)"},
           "skillOverrides": ov}
    if warnings:
        doc["warnings"] = warnings
    return doc


def render_report(data: dict) -> str:
    st, k = data["stats"], data["window_sessions"]
    head = "# Skill health" + ("" if k >= MIN_WINDOW else " (Window too small for telemetry rules)")
    seen = {n: s for n, s in st.items() if s["pushed"] or s["invoked"]}
    rows = sorted(seen.items(), key=lambda kv: (-kv[1]["pushed"], kv[0]))
    out = [head, "", "| skill | pushed | invoked | ratio | flags |", "|---|---|---|---|---|"]
    for name, s in rows:
        ratio = "-" if s["ratio"] is None else f"{s['ratio']:.2f}"
        out.append(f"| {name} | {s['pushed']} | {s['invoked']} | {ratio} | {' '.join(s['flags'])} |")
    never_inv = [n for n, s in rows if "never-invoked" in s["flags"]]
    never_push = [n for n, s in rows if "never-pushed" in s["flags"]]
    dmi = [n for n, s in st.items() if "dmi" in s["flags"]]
    out += ["", f"Pushed, never invoked ({len(never_inv)}): {', '.join(never_inv) or '-'}",
            f"Invoked, never pushed ({len(never_push)}): {', '.join(never_push) or '-'}",
            f"disable-model-invocation ({len(dmi)}): {', '.join(dmi) or '-'}",
            f"Untouched local skills: {len(st) - len(seen)}",
            f"Window: {k} sessions, {data['pushed_rows']} pushed rows, {data['invocation_rows']} invocation rows, "
            f"{data['skipped_lines']} malformed lines"]
    out += [f"note: {n}" for n in data["notes"]]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--root", default=str(ROOT))
    ap.add_argument("--telemetry")
    ap.add_argument("--window", type=int, default=30)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--report", action="store_true")
    mode.add_argument("--json", action="store_true")
    mode.add_argument("--overrides", action="store_true")
    ap.add_argument("--out")
    a = ap.parse_args(argv)
    root = Path(a.root).expanduser().resolve()
    try:
        data = collect(root, telemetry_dir(root, a.telemetry), a.window)
    except OSError as exc:
        print(f"skill-health: ERROR unreadable inventory: {exc}", file=sys.stderr)
        return 1
    if a.overrides:
        doc = overrides_doc(data, root)
        out = Path(a.out).expanduser() if a.out else root / "docs" / "merge" / "skill-overrides.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        with open(out, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(json.dumps(doc, indent=1, sort_keys=True) + "\n")
        counts = {v: sum(1 for x in doc["skillOverrides"].values() if x == v) for v in LEGAL}
        print(f"skill-health: {len(doc['skillOverrides'])} overrides -> {out} "
              f"({', '.join(f'{v}={n}' for v, n in counts.items())}; window {data['window_sessions']} sessions)")
        for w in doc.get("warnings", []):
            print(f"skill-health: WARN {w}")
        return 0
    if a.json:
        print(json.dumps({k: v for k, v in data.items() if k != "inventory"}, indent=1, sort_keys=True))
        return 0
    print(render_report(data))
    return 0


if __name__ == "__main__":
    sys.exit(main())
