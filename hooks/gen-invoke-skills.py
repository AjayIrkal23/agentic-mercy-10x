"""
gen-invoke-skills.py — generate the /invoke skill family from config (v4: skills, not commands).

Output is deterministic (no timestamps), so `--check` is an exact comparison.

  skills/invoke/SKILL.md                         parametric `/invoke <acts...> [-- task]`
  skills/invoke/references/rosters.md            fallback skill rosters (read only when the Agent tool is unavailable)
  skills/invoke-<act>/SKILL.md                   one forked single-act delegator per act (context: fork + agent:)
  skills/invoke-{session,status,update}/SKILL.md utilities

Sources of truth (the act table lives ONLY in config):
  hooks/autonomous-skill-router.config.json
      categories.<CAT>.{act, order, mutates, agent, artifact, checkpoint, requires, local_skills, superpowers_skills}
      orchestration.{closers_chain, closers_parallel, security_trigger_globs}
  hooks/model-policy.json  invoke_categories (per-act model; default sonnet)

    python3 ~/.claude/hooks/gen-invoke-skills.py           # write
    python3 ~/.claude/hooks/gen-invoke-skills.py --check   # exit 1 on drift: missing, stale, or unexpected invoke-* skills
"""
